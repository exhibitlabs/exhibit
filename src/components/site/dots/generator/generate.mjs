// Prints every drawing in drawings.mjs onto its dot grids and writes ../art-data.ts and ../art-small.ts.
//   node src/components/site/dots/generator/generate.mjs [out-dir]
// Pure Node: no browser, no fonts, no network. It also prints each grid to the terminal, so a change can
// be checked before opening the site. Then run export-svg.mjs to refresh the brand files in docs/brand/dots.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { PIECES, WORDMARK } from "./drawings.mjs";
import { canvas } from "./raster.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const dir = process.argv[2] || join(here, "..");
const quiet = process.env.QUIET === "1";

/** lg is the site's grid (pieces 180 px wide and up); sm is for 96 to 179 px (the app's empty states). */
const SIZES = { lg: [60, 45], sm: [32, 24] };

function print(draw, cols, rows) {
  const c = canvas(cols, rows);
  draw(c);
  return c.rowsOut();
}

function show(name, rows) {
  if (quiet) return;
  console.log(`\n${name} (${rows[0].length} x ${rows.length})`);
  for (const r of rows) console.log("  " + r.replace(/\./g, " "));
}

const lit = (rows, indent) => `[\n${rows.map((r) => `${indent}  "${r}",`).join("\n")}\n${indent}]`;
const HEAD = `// Generated by generator/generate.mjs from generator/drawings.mjs. Do not edit by hand: change the
// drawing and run \`node src/components/site/dots/generator/generate.mjs\`.
// One glyph per cell: "." paper, ":" faint ring, "o" ring, "+" small dot, "*" large dot, "#" full dot,
// "@" full dot in gold. paint.ts prints them as SVG.
`;

const names = Object.keys(PIECES);
const grids = { lg: {}, sm: {} };
for (const name of names)
  for (const [size, [cols, rows]] of Object.entries(SIZES)) {
    grids[size][name] = print((c) => PIECES[name][size](c), cols, rows);
    show(`${name} ${size}`, grids[size][name]);
  }
const marks = {};
for (const [name, { s, draw }] of Object.entries(WORDMARK)) {
  const rows = 5 * s;
  const cols = draw(canvas(400, rows), s); // dry run: the drawing returns the width it used
  marks[name] = print((c) => draw(c, s), cols, rows);
  show(`wordmark ${name}`, marks[name]);
}

mkdirSync(dir, { recursive: true });
writeFileSync(
  join(dir, "art-data.ts"),
  `${HEAD}
import type { DotGrid } from "./paint";

export type DotArtName = ${names.map((n) => JSON.stringify(n)).join(" | ")};

/** Every piece on the site's 60 x 45 grid. The 32 x 24 versions for small placements are in art-small.ts. */
export const DOT_ART: Record<DotArtName, DotGrid> = {
${names.map((n) => `  ${n}: ${lit(grids.lg[n], "  ")},`).join("\n")}
};

/** The footer wordmark: fine from 640 px up, coarse on phones. */
export const DOT_WORDMARK: Record<"fine" | "coarse", DotGrid> = {
${Object.entries(marks)
  .map(([n, g]) => `  ${n}: ${lit(g, "  ")},`)
  .join("\n")}
};
`,
);
writeFileSync(
  join(dir, "art-small.ts"),
  `${HEAD}
import type { DotArtName } from "./art-data";
import type { DotGrid } from "./paint";

/** Every piece redrawn for a 32 x 24 grid, for placements 96 to 179 px wide (the app's empty states). */
export const DOT_ART_SMALL: Record<DotArtName, DotGrid> = {
${names.map((n) => `  ${n}: ${lit(grids.sm[n], "  ")},`).join("\n")}
};
`,
);
console.log(`\nwrote ${join(dir, "art-data.ts")} and art-small.ts`);
